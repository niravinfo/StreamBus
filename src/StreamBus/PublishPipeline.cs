using System.Diagnostics;

namespace StreamBus;

/// <summary>
/// Universal publish filter that runs for every typed publish on the bus.
/// </summary>
/// <remarks>
/// Filter instances are resolved once when the bus is built and cached for the
/// bus lifetime, so a filter must be thread-safe. Register filter types with a
/// singleton lifetime: a scoped or transient registration is rejected when the
/// bus is built. Scoped services are available through
/// <see cref="PublishContext.Services"/>.
/// </remarks>
public interface IStreamPublishFilter
{
    /// <summary>
    /// Runs before the publish is serialized and sent.
    /// </summary>
    /// <param name="context">The shared publish context for this message.</param>
    /// <param name="next">The continuation; call it exactly once and await the returned task before returning.</param>
    /// <returns>A task that completes when the filter and its continuation finish.</returns>
    Task OnPublish(PublishContext context, PublishNext next);
}

/// <summary>
/// Publish filter that runs only for publishes whose declared pipe type is
/// <typeparamref name="T"/>.
/// </summary>
/// <typeparam name="T">The declared message type.</typeparam>
/// <remarks>
/// Filter instances are resolved once when the bus is built and cached for the
/// bus lifetime, so a filter must be thread-safe. Register filter types with a
/// singleton lifetime: a scoped or transient registration is rejected when the
/// bus is built. Scoped services are available through
/// <see cref="PublishContext.Services"/>.
/// </remarks>
public interface IStreamPublishFilter<T>
{
    /// <summary>
    /// Runs before the publish is serialized and sent.
    /// </summary>
    /// <param name="context">The typed publish context for this message.</param>
    /// <param name="next">The continuation; call it exactly once and await the returned task before returning.</param>
    /// <returns>A task that completes when the filter and its continuation finish.</returns>
    Task OnPublish(PublishContext<T> context, PublishNext next);
}

/// <summary>
/// Continues a publish pipeline. Publish filters must invoke it exactly once
/// and await the returned task before returning.
/// </summary>
public delegate Task PublishNext();

/// <summary>
/// Shared context for one typed publish. Universal and typed publish filters
/// receive the same context instance.
/// </summary>
public class PublishContext
{
    /// <summary>
    /// Construction is pinned to library code (and test assemblies via
    /// <see langword="InternalsVisibleTo"/>): filters receive and enrich a
    /// context built by StreamBus; they never construct their own.
    /// </summary>
    protected internal PublishContext() { }

    /// <summary>Target stream resolved by the publish call.</summary>
    public required string Stream { get; init; }

    /// <summary>Routing key for a super-stream publish; null for a plain stream.</summary>
    public required string? RoutingKey { get; init; }

    /// <summary>
    /// Published payload. Universal filters can observe it; publish filters
    /// cannot replace the body.
    /// </summary>
    public required object Payload { get; init; }

    /// <summary>AMQP <c>message-id</c> sent with this publish.</summary>
    public required Guid MessageId { get; init; }

    /// <summary>AMQP <c>correlation-id</c>; never generated by StreamBus.</summary>
    public Guid? CorrelationId { get; init; }

    /// <summary>AMQP <c>creation-time</c>, UTC and millisecond precision.</summary>
    public required DateTime SentTime { get; init; }

    /// <summary>Headers that are sent with the publish.</summary>
    public required IStreamSendHeaders Headers { get; init; }

    /// <summary>
    /// Per-publish service scope. Publish filters are singletons, so scoped
    /// services must be resolved here rather than injected into a filter.
    /// </summary>
    public required IServiceProvider Services { get; init; }

    /// <summary>Cancellation token for the publish.</summary>
    public required CancellationToken CancellationToken { get; init; }
}

/// <summary>
/// Typed publish context for a declared message type. It derives from and is
/// the same object as the universal <see cref="PublishContext"/>.
/// </summary>
/// <typeparam name="T">The declared message type.</typeparam>
public sealed class PublishContext<T> : PublishContext
{
    /// <summary>
    /// The payload captured as <typeparamref name="T"/> at construction, so
    /// <see cref="Message"/> does not re-cast (and re-unbox for value types)
    /// <see cref="PublishContext.Payload"/> on every access. Falls back to a
    /// cast when not set (e.g. contexts constructed in tests).
    /// </summary>
    internal T? TypedPayload { get; init; }

    /// <summary>The published payload as <typeparamref name="T"/>.</summary>
    public T Message => TypedPayload is { } typed ? typed : (T)Payload;
}

internal sealed class PublishPipeline
{
    private readonly IStreamPublishFilter[] _filters;

    public PublishPipeline(IReadOnlyList<IStreamPublishFilter> filters)
    {
        ArgumentNullException.ThrowIfNull(filters);
        _filters = filters.ToArray();
    }

    public int Count => _filters.Length;

    public Task RunAsync(PublishContext context, PublishNext terminal)
    {
        ArgumentNullException.ThrowIfNull(context);
        ArgumentNullException.ThrowIfNull(terminal);
        return RunMeasuredAsync(context, terminal);
    }

    private async Task RunMeasuredAsync(PublishContext context, PublishNext terminal)
    {
        var started = Stopwatch.GetTimestamp();
        try
        {
            await InvokeAsync(0, context, terminal).ConfigureAwait(false);
        }
        finally
        {
            StreamBusMetrics.Shared.RecordPipelineDuration("publish", Stopwatch.GetElapsedTime(started).TotalSeconds);
        }
    }

    private async Task InvokeAsync(int index, PublishContext context, PublishNext terminal)
    {
        if (index == _filters.Length)
        {
            await terminal().ConfigureAwait(false);
            return;
        }

        var filter = _filters[index];
        var filterType = FilterIdentity.TypeOf(filter);
        var filterName = filterType.FullName ?? filterType.Name;

        // next must be awaited exactly once within the filter's returned task
        // (documented on PublishNext); the pipeline enforces that below, so the
        // call count never needs cross-thread visibility.
        var nextCalls = 0;
        Task? nextTask = null;
        Task Next()
        {
            nextCalls++;
            if (nextCalls > 1)
            {
                throw new StreamBusFilterContractException(
                    $"Publish filter {filterName} invoked next {nextCalls} times; exactly one continuation is allowed.");
            }

            // Stream, routing key, payload, identity and services are resolved
            // before the pipeline; a filter can only mutate Headers in place.
            nextTask = InvokeAsync(index + 1, context, terminal);
            return nextTask;
        }

        await filter.OnPublish(context, Next).ConfigureAwait(false);

        var calls = nextCalls;
        if (calls == 0)
        {
            throw new StreamBusFilterContractException(
                $"Publish filter '{filterName}' returned without calling next; the message would have been silently dropped.");
        }
        if (calls > 1)
        {
            throw new StreamBusFilterContractException(
                $"Publish filter {filterName} invoked next {calls} times; exactly one continuation is allowed.");
        }
        if (nextTask is not { IsCompleted: true })
        {
            // The filter called next but returned before awaiting it: the
            // continuation (including the send) is still running while the
            // pipeline would report completion, so publish results and faults
            // would escape unobserved. Reject loudly instead.
            throw new StreamBusFilterContractException(
                $"Publish filter '{filterName}' returned before its continuation completed; await next().");
        }
    }
}
